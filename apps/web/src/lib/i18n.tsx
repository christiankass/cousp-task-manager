export type Locale = keyof typeof dictionaries;
export type MessageKey = keyof (typeof dictionaries)["fr"];

type I18n = { locale: Locale; setLocale: (l: Locale) => void; t: (k: MessageKey) => string; tx: (k: string) => string };

const I18nContext = createContext<I18n>({
  locale: "fr",
  setLocale: () => undefined,
  t: (k) => dictionaries.fr[k],
  tx: (k) => (dictionaries.fr as Record<string, string>)[k] ?? k,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("fr");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("locale");
      if (saved === "fr" || saved === "en") setLocaleState(saved);
    } catch {}
  }, []);

  const setLocale = (l: Locale) => {
    setLocaleState(l);
    try {
      localStorage.setItem("locale", l);
    } catch {}
  };

  return (
    <I18nContext.Provider
      value={{
        locale,
        setLocale,
        t: (k) => dictionaries[locale][k],
        tx: (k) => (dictionaries[locale] as Record<string, string>)[k] ?? k,
      }}
    >{children}</I18nContext.Provider>
  );
}

export const useI18n = () => useContext(I18nContext);
